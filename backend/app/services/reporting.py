DEFAULT_BRANDING = {
    "company_name": "MarketEngine",
    "primary_color": "#6d5ef6",
    "accent_color": "#10b981",
    "logo_url": None,
    "footer_note": None,
}

# Anything outside this is dropped rather than rendered. The branding dict
# reaches an HTML template, so an unbounded blob here would be a way to put
# arbitrary markup into a PDF the workspace's clients receive.
ALLOWED_BRANDING_KEYS = frozenset(DEFAULT_BRANDING)


def sanitise_branding(raw: Optional[dict], *, entitled: bool) -> dict:
    """The branding to render with.

    Without the ``white_label`` entitlement the customer's own branding is
    ignored and the product's defaults are used -- not an error, because a
    report is still worth having, and a hard failure on the plan boundary would
    mean a scheduled report silently stops arriving the month a plan changes.
    """
    branding = dict(DEFAULT_BRANDING)
    if not entitled or not raw:
        return branding

    for key in ALLOWED_BRANDING_KEYS:
        value = raw.get(key)
        if value is None:
            continue
        if key.endswith("_color"):
            text = str(value).strip()
            # Only a hex literal reaches the stylesheet.
            if len(text) in (4, 7) and text.startswith("#") and all(
                ch in "0123456789abcdefABCDEF" for ch in text[1:]
            ):
                branding[key] = text
        elif key == "logo_url":
            text = str(value).strip()
            if text.startswith(("https://", "http://")):
                branding[key] = text
        else:
            branding[key] = str(value)[:120]
    return branding
